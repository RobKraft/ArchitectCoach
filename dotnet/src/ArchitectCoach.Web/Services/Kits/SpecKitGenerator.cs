using System.Text;
using ArchitectCoach.Web.Content;
using ArchitectCoach.Web.Domain;

namespace ArchitectCoach.Web.Services.Kits;

/// <summary>
/// The GitHub Spec Kit–compatible part of the download (port of the Next.js
/// src/lib/speckit/generate.ts, checked byte for byte against its output by the golden-file
/// tests). Writes nothing into Spec Kit's own managed paths (.specify/, specs/), only inputs for
/// each Spec Kit command plus AGENTS.md (ADR-0008). No AI call happens here.
/// </summary>
public sealed class SpecKitGenerator(ContentCatalog content, WizardService wizard)
{
    private const string Dir = "architectcoach";

    private sealed record Assessed(WizardStep Step, WizardOption Option, OptionAssessment? Assessment);

    public IReadOnlyDictionary<string, string> Generate(Project project)
    {
        var type = project.ProjectType;
        var choices = wizard.ResolveChoices(project)
            .Select(c => new Assessed(c.Step, c.Option, content.AssessmentsFor(c.Step.Id)?.GetValueOrDefault(c.Option.Id)))
            .ToList();
        var questions = CollectOpenQuestions(type, choices);

        return new Dictionary<string, string>
        {
            ["SPEC-KIT-START-HERE.md"] = StartHere(type),
            ["AGENTS.md"] = Agents(type),
            ["CLAUDE.md"] = PointerToAgents(),
            [".github/copilot-instructions.md"] = PointerToAgents(),
            [$"{Dir}/decisions.md"] = Decisions(type, project.Knowledge, choices),
            [$"{Dir}/open-questions.md"] = OpenQuestions(questions),
            [$"{Dir}/constitution-input.md"] = ConstitutionInput(type, choices),
            [$"{Dir}/feature-brief.md"] = FeatureBrief(type, project.Knowledge),
            [$"{Dir}/tech-context.md"] = TechContext(choices),
            [$"{Dir}/privacy-and-accessibility.md"] = content.PrivacyAccessibility.MarkdownByProjectType.GetValueOrDefault(type, ""),
        }.ToDictionary(kv => kv.Key, kv => Lf(kv.Value));
    }

    /// <summary>Universal, then project-type, then per-pick questions; first occurrence wins.</summary>
    private List<OpenQuestion> CollectOpenQuestions(string type, IEnumerable<Assessed> choices)
    {
        var all = content.OpenQuestions.Universal
            .Concat(content.OpenQuestions.ByProjectType.GetValueOrDefault(type, []))
            .Concat(choices.SelectMany(c => content.OpenQuestions.ByOption.GetValueOrDefault($"{c.Step.Id}/{c.Option.Id}", [])));
        var seen = new HashSet<string>();
        return all.Where(q => seen.Add(q.Question)).ToList();
    }

    internal static string Lf(string s) => s.Replace("\r\n", "\n");

    private static string Bullets(IEnumerable<string> items, string empty = "_None recorded._")
    {
        var list = items.ToList();
        return list.Count > 0 ? string.Join("\n", list.Select(i => $"- {i}")) : empty;
    }

    private static string StartHere(string type) => $$"""
        # Start here: your {{type}} Spec Kit

        This kit was generated by ArchitectCoach from the decisions you made in its wizard. It's built to
        work with [GitHub Spec Kit](https://github.com/github/spec-kit) — spec-driven development where
        your AI coding agent writes a **spec → plan → task list**, then builds from it.

        ArchitectCoach already settled the big architecture choices. Your AI agent will ask you the rest
        (the questions in `{{Dir}}/open-questions.md`), then write the spec, plan, and tasks with you.

        ## What's in the kit

        | File | What it's for |
        |---|---|
        | `AGENTS.md` | Instructions your AI agent follows (`CLAUDE.md` and `.github/copilot-instructions.md` point to it). |
        | `{{Dir}}/decisions.md` | Every choice you made, with tradeoffs, cost, security, scale, compliance, auditing, and performance notes. |
        | `{{Dir}}/open-questions.md` | What still needs answering, and why each question matters. Your agent fills in the answers with you. |
        | `{{Dir}}/constitution-input.md` | Input for `/speckit.constitution` — your project's non-negotiable principles. |
        | `{{Dir}}/feature-brief.md` | Input for `/speckit.specify` — what you're building and why (no tech details). |
        | `{{Dir}}/tech-context.md` | Input for `/speckit.plan` — the technology already chosen. |
        | `{{Dir}}/privacy-and-accessibility.md` | PII inventory, GDPR/CCPA checklists, and the WCAG 2.2 AA checklist for this kind of project. Required, not optional. |

        ## Steps

        1. **Create a project folder**, unzip this kit into it, then run `git init` and commit. Committing
           first lets you review exactly what Spec Kit adds in the next step.
        2. **Install the Spec Kit CLI** (needs Python 3.11+ and [uv](https://docs.astral.sh/uv/)):
           ```
           uv tool install specify-cli
           ```
        3. **Add Spec Kit to the folder** for the AI agent you use (for example `claude`, `copilot`,
           `codex`, `cursor-agent`, `gemini` — see Spec Kit's integrations reference for the full list):
           ```
           specify init --here --integration claude
           ```
           If it refuses because the folder isn't empty, add `--force`. Spec Kit only replaces its own
           files; everything ArchitectCoach generated lives in `{{Dir}}/`, which Spec Kit doesn't manage.
           Check `git diff` afterward — if it changed `AGENTS.md` or `CLAUDE.md`, keep both parts.
        4. **Open your AI agent in the folder and say:** _"Read AGENTS.md and start."_ It will interview
           you, then run the Spec Kit steps below, stopping for your review after each one.

        ## The Spec Kit sequence (what your agent runs)

        Command names vary by agent: `/speckit.plan` in Spec Kit's docs may appear as `/speckit-plan`
        or `$speckit-plan` in your tool. Same commands, different spelling.

        | Step | Command | Input from this kit |
        |---|---|---|
        | 1 | `/speckit.constitution` | `{{Dir}}/constitution-input.md` + answered budget/compliance questions |
        | 2 | `/speckit.specify` | `{{Dir}}/feature-brief.md` + answered "spec" questions |
        | 3 | `/speckit.clarify` | Remaining "spec" questions in `{{Dir}}/open-questions.md` |
        | 4 | `/speckit.plan` | `{{Dir}}/tech-context.md` + answered "plan" questions |
        | 5 | `/speckit.tasks` | The plan from step 4 |
        | 6 | `/speckit.analyze` (if available) | Checks spec, plan, and tasks agree |
        | 7 | `/speckit.implement` | Builds the tasks, one at a time |

        **No Spec Kit?** `AGENTS.md` includes a fallback that produces the same spec, plan, and tasks
        files without it.

        """;

    private static string Agents(string type) => $$"""
        # Instructions for AI agents working in this repository

        This is a **{{type}}** project. The developer used ArchitectCoach to make the main
        architecture decisions; your job is to help them finish the specification, plan, and task list
        with GitHub Spec Kit, then build it. Act as a patient architecture coach, not just an executor.

        ## Ground rules

        1. **Decisions in `{{Dir}}/decisions.md` are settled.** Don't re-open them unless the developer
           asks, or an answer they give makes one unworkable. If that happens, say which decision and
           why, and let them decide. Record any change as a new entry at the bottom of that file.
        2. **Ask, don't assume.** Never invent an answer to a question in `{{Dir}}/open-questions.md`.
           Ask **one question at a time**, say in a sentence why it matters, and offer two or three
           sensible example answers when the developer is unsure.
        3. **Write answers down immediately.** Replace the question's `**Answer:** _(pending)_` line with
           the developer's answer as soon as you have it, so nothing is lost if the session ends.
           If they choose to skip one, write `**Answer:** Deferred — <reason>`.
        4. **Stop for review after each step** below. Summarize what you produced and ask for approval
           before moving on.
        5. Keep explanations plain — the developer may be early in their career.
        6. If a `docs/` folder exists (coding and testing standards, checklists, Definition of Done,
           ADRs), its rules apply to the plan, the tasks, and every line of code you write.
        7. **Privacy and accessibility are requirements.** Follow `{{Dir}}/privacy-and-accessibility.md`.
           Collect only the personal data the spec needs. Every UI task's "done" check includes a
           keyboard check and an automated accessibility check (WCAG 2.2 AA). Every task that stores
           personal data names its retention period and how it gets deleted.

        ## Process

        1. **Interview — spec questions.** Read `{{Dir}}/decisions.md`, then ask every question marked
           _phase: spec_ in `{{Dir}}/open-questions.md` that isn't answered yet.
        2. **Constitution.** Run `/speckit.constitution`, giving it `{{Dir}}/constitution-input.md` plus
           the answers about budget, compliance, sensitive data, and performance.
        3. **Specify.** Run `/speckit.specify` with `{{Dir}}/feature-brief.md` plus the answered spec
           questions. Keep it about *what* and *why* — no technology choices in the spec.
        4. **Clarify.** Run `/speckit.clarify`. Answer what you can from `{{Dir}}/open-questions.md`;
           ask the developer the rest, and record new answers there too.
        5. **Interview — plan questions.** Ask every unanswered question marked _phase: plan_.
        6. **Plan.** Run `/speckit.plan` with `{{Dir}}/tech-context.md` plus the answered plan questions.
           Check the plan against the security, compliance, cost, and auditing notes in
           `{{Dir}}/decisions.md` and add anything missing (budget alerts, monitoring, backups).
           The plan must include a filled-in **PII inventory** (template in
           `{{Dir}}/privacy-and-accessibility.md`), how each GDPR/CCPA right that applies will be met,
           and the **accessibility test approach**.
        7. **Tasks.** Run `/speckit.tasks`. Each task should be small enough to finish and verify in one
           sitting and have a clear "done" check.
        8. **Analyze.** Run `/speckit.analyze` if available, and fix any inconsistencies it reports.
        9. **Implement.** Only after the developer approves the task list, run `/speckit.implement`.
           Work one task at a time and check it off.

        Spec Kit command names vary by agent (`/speckit.plan`, `/speckit-plan`, `$speckit-plan`) — use
        whichever form your environment provides.

        ## Fallback if Spec Kit isn't installed

        Follow the same process, writing these files yourself:
        - `specs/001-first-release/spec.md` — user stories, acceptance criteria, non-goals, open risks.
        - `specs/001-first-release/plan.md` — architecture, data model, components and accounts,
          environments, security/compliance measures, cost guardrails, monitoring, milestones.
        - `specs/001-first-release/tasks.md` — numbered checklist; each task lists what it depends on
          and how to verify it.
        Put the constitution in `memory/constitution.md`. Suggest installing Spec Kit
        (`uv tool install specify-cli`) if the developer wants the full workflow.

        """;

    private static string PointerToAgents() => """
        # Agent instructions

        Follow the instructions in [AGENTS.md](AGENTS.md) at the repository root. Start with
        `SPEC-KIT-START-HERE.md` if you need the overview.

        """;

    private string AssessmentMarkdown(OptionAssessment a) => string.Join("\n", content.Assessments.Dimensions.Select(d => d.Key switch
    {
        "deployment" => $"- **{d.Label}:** {a.Deployment.Complexity}. {a.Deployment.Notes}",
        "components" => $"- **{d.Label}:** {(a.Components.Accounts.Count > 0 ? string.Join("; ", a.Components.Accounts) : "None")}. {a.Components.Notes}",
        "cost" => $"- **{d.Label}:** {a.Cost.Bucket}. {a.Cost.Notes}",
        "scalability" => $"- **{d.Label}:** {a.Scalability.Level}. {a.Scalability.Notes}",
        "security" => $"- **{d.Label}:** {a.Security}",
        "grc" => $"- **{d.Label}:** {a.Grc}",
        "auditing" => $"- **{d.Label}:** {a.Auditing}",
        "costMonitoring" => $"- **{d.Label}:** {a.CostMonitoring}",
        "performance" => $"- **{d.Label}:** {a.Performance}",
        _ => throw new InvalidOperationException($"Unknown assessment dimension '{d.Key}'."),
    }));

    private string Decisions(string type, ProjectKnowledge k, IReadOnlyList<Assessed> choices)
    {
        var sections = choices.Select(c =>
        {
            var alternatives = c.Step.Options.Where(o => o.Id != c.Option.Id).Select(o => o.Label);
            var practice = c.Assessment is null ? "" : $"\n### What this means in practice\n\n{AssessmentMarkdown(c.Assessment)}\n";
            return $"## {c.Step.Question}\n\n**Chosen:** {c.Option.Label}\n\n{c.Option.Summary}\n\n**Tradeoffs:** {c.Option.Tradeoffs}\n\n**Alternatives not chosen:** {string.Join("; ", alternatives)}\n{practice}";
        });
        var purpose = string.IsNullOrEmpty(k.Requirements.Purpose) ? "_Not stated — ask the developer._" : k.Requirements.Purpose;

        return $"# Decisions already made — {type}\n\n" +
               "Made in ArchitectCoach's wizard. Treat these as settled (see AGENTS.md, rule 1).\n" +
               $"Cost figures are rough monthly ballparks as of {content.Assessments.AsOf}; check current vendor pricing.\n\n" +
               $"**Purpose:** {purpose}\n\n" +
               string.Join("\n", sections) +
               "\n## Changes after the wizard\n\n" +
               "_Record any decision changed during spec/plan work here: what changed, why, and what it affects._\n";
    }

    private static string OpenQuestions(IReadOnlyList<OpenQuestion> questions)
    {
        string Render(string phase, int startAt) => string.Join("\n", questions.Where(q => q.Phase == phase).Select((q, i) =>
            $"### Q{startAt + i:00}. {q.Question}\n\n_phase: {phase}_ — {q.WhyItMatters}\n\n**Answer:** _(pending)_\n"));

        var specCount = questions.Count(q => q.Phase == "spec");
        return "# Open questions\n\n" +
               "ArchitectCoach's wizard settled the main architecture choices. These questions are still open.\n" +
               "Your AI agent asks them one at a time and writes each answer here (see AGENTS.md).\n\n" +
               "## Spec questions — answer before/during `/speckit.specify` and `/speckit.clarify`\n\n" +
               Render("spec", 1) +
               "\n## Plan questions — answer before `/speckit.plan`\n\n" +
               Render("plan", specCount + 1);
    }

    private static string ConstitutionInput(string type, IReadOnlyList<Assessed> choices)
    {
        var assessed = choices.Where(c => c.Assessment is not null).ToList();
        string FromEach(Func<OptionAssessment, string> pick) => Bullets(assessed.Select(c => $"_{c.Option.Label}:_ {pick(c.Assessment!)}"));

        return $"# Constitution input — {type}\n\n" + $$"""
            Give this to `/speckit.constitution`, together with the answers to the budget, compliance,
            sensitive-data, user-location, accessibility, and performance questions in `open-questions.md`.
            These are the principles every spec, plan, and task must respect.

            ## 1. The architecture decisions are binding

            {{Bullets(choices.Select(c => $"{c.Step.Question} → **{c.Option.Label}**"))}}

            Changing one requires recording why in `decisions.md` ("Changes after the wizard") first.

            ## 2. Simplicity first

            Build the smallest thing that meets the spec. No extra services, layers, or abstractions
            without a stated reason tied to a requirement.

            ## 3. Every task is verifiable

            Each task has a "done" check — an automated test where practical, otherwise a written manual
            check. Nothing is done until its check passes.

            ## 4. Privacy by design

            Collect the minimum personal data the spec requires. Every personal-data field has a stated
            purpose, a retention period, and a deletion path, all recorded in the PII inventory. Users can
            see, export, and delete their data where privacy law (GDPR, CCPA) applies. No tracking or
            advertising cookies without opt-in consent. Never log personal data, passwords, or tokens.
            Details: `privacy-and-accessibility.md`.

            ## 5. Accessible by default

            Every user interface meets **WCAG 2.2 AA**. Accessibility is part of "done" for every UI task:
            keyboard operable, screen-reader labeled, sufficient contrast, and checked with automated tools
            plus a manual pass. Details: `privacy-and-accessibility.md`.

            ## 6. Security

            {{FromEach(a => a.Security)}}

            ## 7. Governance, risk & compliance

            {{FromEach(a => a.Grc)}}

            ## 8. Cost guardrails

            Set a budget alert on every paid account at the monthly limit from `open-questions.md`.

            {{FromEach(a => a.CostMonitoring)}}

            ## 9. Auditing for correctness

            {{FromEach(a => a.Auditing)}}

            ## 10. Performance

            {{FromEach(a => a.Performance)}}

            """;
    }

    private static string FeatureBrief(string type, ProjectKnowledge k)
    {
        var r = k.Requirements;
        var build = string.IsNullOrEmpty(r.Purpose) ? $"Build a {type.ToLowerInvariant()}." : $"Build a {type.ToLowerInvariant()}: {r.Purpose}";
        var nonGoals = r.NonGoals.Count > 0 ? $"\n**Not in scope:**\n{Bullets(r.NonGoals)}\n" : "";

        return "# Feature brief — first release\n\n" +
               "Give this to `/speckit.specify`. It describes **what** to build and **why**, not how; the\n" +
               "technology is in `tech-context.md` and belongs in the plan, not the spec.\n\n" +
               $"{build}\n\n" +
               $"**Who it's for:**\n{Bullets(r.Users)}\n\n" +
               $"**What it must achieve:**\n{Bullets(r.Goals)}\n" +
               nonGoals +
               "\n**Still to define with the developer** (from `open-questions.md`, phase: spec): the key user\n" +
               "journeys, what's out of scope, how success is measured, expected volume, sensitive data,\n" +
               "compliance needs, and acceptable performance.\n";
    }

    private string TechContext(IReadOnlyList<Assessed> choices)
    {
        var assessed = choices.Where(c => c.Assessment is not null).ToList();
        var accounts = new List<string>();
        var seen = new HashSet<string>();
        foreach (var account in assessed.SelectMany(c => c.Assessment!.Components.Accounts))
            if (seen.Add(account)) accounts.Add(account);

        var rows = string.Join("\n", assessed.Select(c =>
            $"| {c.Step.Question} | {c.Option.Label} | {c.Assessment!.Deployment.Complexity} | {c.Assessment.Cost.Bucket} | {c.Assessment.Scalability.Level} |"));
        if (rows.Length == 0) rows = "| _No architecture/technology decisions recorded_ | | | | |";

        return $$"""
            # Technical context

            Give this to `/speckit.plan`, together with the answered "plan" questions in `open-questions.md`.

            ## Chosen technology and architecture

            | Decision | Chosen | Deployment complexity | Ballpark cost | Scalability |
            |---|---|---|---|---|
            {{rows}}

            Cost buckets are rough monthly figures as of {{content.Assessments.AsOf}}.

            ## Accounts and integrations the plan must cover

            Each needs an owner, credentials stored safely, and (if paid) a budget alert:

            {{Bullets(accounts)}}

            ## The plan must include

            - Environments and how code gets from a commit to production.
            - Where secrets live, and who has access to each account above.
            - Monitoring and alerting for errors, uptime, and cost.
            - Backups and a tested restore, if any data is stored.
            - How each security and compliance principle in the constitution is met.
            - Specific tools where the wizard only chose a category (see the "plan" questions).

            """;
    }
}
