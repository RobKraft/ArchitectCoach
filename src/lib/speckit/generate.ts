import type { ProjectKnowledge } from "@/lib/knowledge/types";
import { resolveWizardChoices, type ResolvedChoice } from "@/lib/wizard/resolveChoices";
import {
  ASSESSMENTS_AS_OF,
  ASSESSMENT_DIMENSIONS,
  getStepAssessments,
  type OptionAssessment,
} from "@/lib/wizard/assessments";
import {
  OPTION_QUESTIONS,
  PROJECT_TYPE_QUESTIONS,
  UNIVERSAL_QUESTIONS,
  type OpenQuestion,
} from "@/lib/speckit/openQuestions";

/**
 * Builds the GitHub Spec Kit–compatible part of the downloadable kit. Deliberately writes
 * nothing into Spec Kit's own managed paths (.specify/, specs/, agent command folders):
 * `specify init --force` may replace those, and their layout differs across Spec Kit versions
 * and agents. Instead it ships inputs for each Spec Kit command under architectcoach/, plus
 * AGENTS.md telling the developer's AI agent how to use them. No AI call happens here.
 * See docs/decisions/0008-spec-kit-compatible-download.md.
 */

const DIR = "architectcoach";

type Assessed = ResolvedChoice & { assessment?: OptionAssessment };

function assessedChoices(projectType: string, knowledge: ProjectKnowledge): Assessed[] {
  return resolveWizardChoices(projectType, knowledge).map((c) => ({
    ...c,
    assessment: getStepAssessments(c.step.id)?.[c.option.id],
  }));
}

function bullets(items: string[], empty = "_None recorded._"): string {
  return items.length ? items.map((i) => `- ${i}`).join("\n") : empty;
}

/** Ordered, de-duplicated open questions for this project's type and picks. */
export function collectOpenQuestions(projectType: string, choices: ResolvedChoice[]): OpenQuestion[] {
  const seen = new Set<string>();
  const all = [
    ...UNIVERSAL_QUESTIONS,
    ...(PROJECT_TYPE_QUESTIONS[projectType] ?? []),
    ...choices.flatMap((c) => OPTION_QUESTIONS[`${c.step.id}/${c.option.id}`] ?? []),
  ];
  return all.filter((q) => (seen.has(q.question) ? false : (seen.add(q.question), true)));
}

export function generateSpecKitFiles(projectType: string, knowledge: ProjectKnowledge): Record<string, string> {
  const choices = assessedChoices(projectType, knowledge);
  const questions = collectOpenQuestions(projectType, choices);

  return {
    "SPEC-KIT-START-HERE.md": buildStartHere(projectType),
    "AGENTS.md": buildAgents(projectType),
    "CLAUDE.md": pointerToAgents(),
    ".github/copilot-instructions.md": pointerToAgents(),
    [`${DIR}/decisions.md`]: buildDecisions(projectType, knowledge, choices),
    [`${DIR}/open-questions.md`]: buildOpenQuestions(questions),
    [`${DIR}/constitution-input.md`]: buildConstitutionInput(projectType, choices),
    [`${DIR}/feature-brief.md`]: buildFeatureBrief(projectType, knowledge),
    [`${DIR}/tech-context.md`]: buildTechContext(choices),
  };
}

function buildStartHere(projectType: string): string {
  return `# Start here: your ${projectType} Spec Kit

This kit was generated by ArchitectCoach from the decisions you made in its wizard. It's built to
work with [GitHub Spec Kit](https://github.com/github/spec-kit) — spec-driven development where
your AI coding agent writes a **spec → plan → task list**, then builds from it.

ArchitectCoach already settled the big architecture choices. Your AI agent will ask you the rest
(the questions in \`${DIR}/open-questions.md\`), then write the spec, plan, and tasks with you.

## What's in the kit

| File | What it's for |
|---|---|
| \`AGENTS.md\` | Instructions your AI agent follows (\`CLAUDE.md\` and \`.github/copilot-instructions.md\` point to it). |
| \`${DIR}/decisions.md\` | Every choice you made, with tradeoffs, cost, security, scale, compliance, auditing, and performance notes. |
| \`${DIR}/open-questions.md\` | What still needs answering, and why each question matters. Your agent fills in the answers with you. |
| \`${DIR}/constitution-input.md\` | Input for \`/speckit.constitution\` — your project's non-negotiable principles. |
| \`${DIR}/feature-brief.md\` | Input for \`/speckit.specify\` — what you're building and why (no tech details). |
| \`${DIR}/tech-context.md\` | Input for \`/speckit.plan\` — the technology already chosen. |

## Steps

1. **Create a project folder**, unzip this kit into it, then run \`git init\` and commit. Committing
   first lets you review exactly what Spec Kit adds in the next step.
2. **Install the Spec Kit CLI** (needs Python 3.11+ and [uv](https://docs.astral.sh/uv/)):
   \`\`\`
   uv tool install specify-cli
   \`\`\`
3. **Add Spec Kit to the folder** for the AI agent you use (for example \`claude\`, \`copilot\`,
   \`codex\`, \`cursor-agent\`, \`gemini\` — see Spec Kit's integrations reference for the full list):
   \`\`\`
   specify init --here --integration claude
   \`\`\`
   If it refuses because the folder isn't empty, add \`--force\`. Spec Kit only replaces its own
   files; everything ArchitectCoach generated lives in \`${DIR}/\`, which Spec Kit doesn't manage.
   Check \`git diff\` afterward — if it changed \`AGENTS.md\` or \`CLAUDE.md\`, keep both parts.
4. **Open your AI agent in the folder and say:** _"Read AGENTS.md and start."_ It will interview
   you, then run the Spec Kit steps below, stopping for your review after each one.

## The Spec Kit sequence (what your agent runs)

Command names vary by agent: \`/speckit.plan\` in Spec Kit's docs may appear as \`/speckit-plan\`
or \`$speckit-plan\` in your tool. Same commands, different spelling.

| Step | Command | Input from this kit |
|---|---|---|
| 1 | \`/speckit.constitution\` | \`${DIR}/constitution-input.md\` + answered budget/compliance questions |
| 2 | \`/speckit.specify\` | \`${DIR}/feature-brief.md\` + answered "spec" questions |
| 3 | \`/speckit.clarify\` | Remaining "spec" questions in \`${DIR}/open-questions.md\` |
| 4 | \`/speckit.plan\` | \`${DIR}/tech-context.md\` + answered "plan" questions |
| 5 | \`/speckit.tasks\` | The plan from step 4 |
| 6 | \`/speckit.analyze\` (if available) | Checks spec, plan, and tasks agree |
| 7 | \`/speckit.implement\` | Builds the tasks, one at a time |

**No Spec Kit?** \`AGENTS.md\` includes a fallback that produces the same spec, plan, and tasks
files without it.
`;
}

function buildAgents(projectType: string): string {
  return `# Instructions for AI agents working in this repository

This is a **${projectType}** project. The developer used ArchitectCoach to make the main
architecture decisions; your job is to help them finish the specification, plan, and task list
with GitHub Spec Kit, then build it. Act as a patient architecture coach, not just an executor.

## Ground rules

1. **Decisions in \`${DIR}/decisions.md\` are settled.** Don't re-open them unless the developer
   asks, or an answer they give makes one unworkable. If that happens, say which decision and
   why, and let them decide. Record any change as a new entry at the bottom of that file.
2. **Ask, don't assume.** Never invent an answer to a question in \`${DIR}/open-questions.md\`.
   Ask **one question at a time**, say in a sentence why it matters, and offer two or three
   sensible example answers when the developer is unsure.
3. **Write answers down immediately.** Replace the question's \`**Answer:** _(pending)_\` line with
   the developer's answer as soon as you have it, so nothing is lost if the session ends.
   If they choose to skip one, write \`**Answer:** Deferred — <reason>\`.
4. **Stop for review after each step** below. Summarize what you produced and ask for approval
   before moving on.
5. Keep explanations plain — the developer may be early in their career.
6. If a \`docs/\` folder exists (coding and testing standards, checklists, Definition of Done,
   ADRs), its rules apply to the plan, the tasks, and every line of code you write.

## Process

1. **Interview — spec questions.** Read \`${DIR}/decisions.md\`, then ask every question marked
   _phase: spec_ in \`${DIR}/open-questions.md\` that isn't answered yet.
2. **Constitution.** Run \`/speckit.constitution\`, giving it \`${DIR}/constitution-input.md\` plus
   the answers about budget, compliance, sensitive data, and performance.
3. **Specify.** Run \`/speckit.specify\` with \`${DIR}/feature-brief.md\` plus the answered spec
   questions. Keep it about *what* and *why* — no technology choices in the spec.
4. **Clarify.** Run \`/speckit.clarify\`. Answer what you can from \`${DIR}/open-questions.md\`;
   ask the developer the rest, and record new answers there too.
5. **Interview — plan questions.** Ask every unanswered question marked _phase: plan_.
6. **Plan.** Run \`/speckit.plan\` with \`${DIR}/tech-context.md\` plus the answered plan questions.
   Check the plan against the security, compliance, cost, and auditing notes in
   \`${DIR}/decisions.md\` and add anything missing (budget alerts, monitoring, backups).
7. **Tasks.** Run \`/speckit.tasks\`. Each task should be small enough to finish and verify in one
   sitting and have a clear "done" check.
8. **Analyze.** Run \`/speckit.analyze\` if available, and fix any inconsistencies it reports.
9. **Implement.** Only after the developer approves the task list, run \`/speckit.implement\`.
   Work one task at a time and check it off.

Spec Kit command names vary by agent (\`/speckit.plan\`, \`/speckit-plan\`, \`$speckit-plan\`) — use
whichever form your environment provides.

## Fallback if Spec Kit isn't installed

Follow the same process, writing these files yourself:
- \`specs/001-first-release/spec.md\` — user stories, acceptance criteria, non-goals, open risks.
- \`specs/001-first-release/plan.md\` — architecture, data model, components and accounts,
  environments, security/compliance measures, cost guardrails, monitoring, milestones.
- \`specs/001-first-release/tasks.md\` — numbered checklist; each task lists what it depends on
  and how to verify it.
Put the constitution in \`memory/constitution.md\`. Suggest installing Spec Kit
(\`uv tool install specify-cli\`) if the developer wants the full workflow.
`;
}

function pointerToAgents(): string {
  return `# Agent instructions

Follow the instructions in [AGENTS.md](AGENTS.md) at the repository root. Start with
\`SPEC-KIT-START-HERE.md\` if you need the overview.
`;
}

function assessmentMarkdown(a: OptionAssessment): string {
  return ASSESSMENT_DIMENSIONS.map(({ key, label }) => {
    switch (key) {
      case "deployment":
        return `- **${label}:** ${a.deployment.complexity}. ${a.deployment.notes}`;
      case "components":
        return `- **${label}:** ${a.components.accounts.length ? a.components.accounts.join("; ") : "None"}. ${a.components.notes}`;
      case "cost":
        return `- **${label}:** ${a.cost.bucket}. ${a.cost.notes}`;
      case "scalability":
        return `- **${label}:** ${a.scalability.level}. ${a.scalability.notes}`;
      default:
        return `- **${label}:** ${a[key]}`;
    }
  }).join("\n");
}

function buildDecisions(projectType: string, k: ProjectKnowledge, choices: Assessed[]): string {
  const sections = choices.map(({ step, option, assessment }) => {
    const alternatives = step.options.filter((o) => o.id !== option.id).map((o) => o.label);
    return `## ${step.question}

**Chosen:** ${option.label}

${option.summary}

**Tradeoffs:** ${option.tradeoffs}

**Alternatives not chosen:** ${alternatives.join("; ")}
${assessment ? `\n### What this means in practice\n\n${assessmentMarkdown(assessment)}\n` : ""}`;
  });

  return `# Decisions already made — ${projectType}

Made in ArchitectCoach's wizard. Treat these as settled (see AGENTS.md, rule 1).
Cost figures are rough monthly ballparks as of ${ASSESSMENTS_AS_OF}; check current vendor pricing.

**Purpose:** ${k.requirements.purpose || "_Not stated — ask the developer._"}

${sections.join("\n")}
## Changes after the wizard

_Record any decision changed during spec/plan work here: what changed, why, and what it affects._
`;
}

function buildOpenQuestions(questions: OpenQuestion[]): string {
  const render = (phase: OpenQuestion["phase"], startAt: number) =>
    questions
      .filter((q) => q.phase === phase)
      .map(
        (q, i) => `### Q${String(startAt + i).padStart(2, "0")}. ${q.question}

_phase: ${phase}_ — ${q.whyItMatters}

**Answer:** _(pending)_
`
      )
      .join("\n");

  const specCount = questions.filter((q) => q.phase === "spec").length;
  return `# Open questions

ArchitectCoach's wizard settled the main architecture choices. These questions are still open.
Your AI agent asks them one at a time and writes each answer here (see AGENTS.md).

## Spec questions — answer before/during \`/speckit.specify\` and \`/speckit.clarify\`

${render("spec", 1)}
## Plan questions — answer before \`/speckit.plan\`

${render("plan", specCount + 1)}`;
}

function buildConstitutionInput(projectType: string, choices: Assessed[]): string {
  const assessed = choices.filter((c): c is Assessed & { assessment: OptionAssessment } => !!c.assessment);
  const fromEach = (pick: (a: OptionAssessment) => string) =>
    bullets(assessed.map((c) => `_${c.option.label}:_ ${pick(c.assessment)}`));

  return `# Constitution input — ${projectType}

Give this to \`/speckit.constitution\`, together with the answers to the budget, compliance,
sensitive-data, and performance questions in \`open-questions.md\`. These are the principles every
spec, plan, and task must respect.

## 1. The architecture decisions are binding

${bullets(choices.map((c) => `${c.step.question} → **${c.option.label}**`))}

Changing one requires recording why in \`decisions.md\` ("Changes after the wizard") first.

## 2. Simplicity first

Build the smallest thing that meets the spec. No extra services, layers, or abstractions
without a stated reason tied to a requirement.

## 3. Every task is verifiable

Each task has a "done" check — an automated test where practical, otherwise a written manual
check. Nothing is done until its check passes.

## 4. Security

${fromEach((a) => a.security)}

## 5. Governance, risk & compliance

${fromEach((a) => a.grc)}

## 6. Cost guardrails

Set a budget alert on every paid account at the monthly limit from \`open-questions.md\`.

${fromEach((a) => a.costMonitoring)}

## 7. Auditing for correctness

${fromEach((a) => a.auditing)}

## 8. Performance

${fromEach((a) => a.performance)}
`;
}

function buildFeatureBrief(projectType: string, k: ProjectKnowledge): string {
  const r = k.requirements;
  return `# Feature brief — first release

Give this to \`/speckit.specify\`. It describes **what** to build and **why**, not how; the
technology is in \`tech-context.md\` and belongs in the plan, not the spec.

Build a ${projectType.toLowerCase()}${r.purpose ? `: ${r.purpose}` : "."}

**Who it's for:**
${bullets(r.users)}

**What it must achieve:**
${bullets(r.goals)}
${r.nonGoals.length ? `\n**Not in scope:**\n${bullets(r.nonGoals)}\n` : ""}
**Still to define with the developer** (from \`open-questions.md\`, phase: spec): the key user
journeys, what's out of scope, how success is measured, expected volume, sensitive data,
compliance needs, and acceptable performance.
`;
}

function buildTechContext(choices: Assessed[]): string {
  const assessed = choices.filter((c) => c.assessment);
  const accounts = [...new Set(assessed.flatMap((c) => c.assessment!.components.accounts))];
  const rows = assessed
    .map(
      ({ step, option, assessment: a }) =>
        `| ${step.question} | ${option.label} | ${a!.deployment.complexity} | ${a!.cost.bucket} | ${a!.scalability.level} |`
    )
    .join("\n");

  return `# Technical context

Give this to \`/speckit.plan\`, together with the answered "plan" questions in \`open-questions.md\`.

## Chosen technology and architecture

| Decision | Chosen | Deployment complexity | Ballpark cost | Scalability |
|---|---|---|---|---|
${rows || "| _No architecture/technology decisions recorded_ | | | | |"}

Cost buckets are rough monthly figures as of ${ASSESSMENTS_AS_OF}.

## Accounts and integrations the plan must cover

Each needs an owner, credentials stored safely, and (if paid) a budget alert:

${bullets(accounts)}

## The plan must include

- Environments and how code gets from a commit to production.
- Where secrets live, and who has access to each account above.
- Monitoring and alerting for errors, uptime, and cost.
- Backups and a tested restore, if any data is stored.
- How each security and compliance principle in the constitution is met.
- Specific tools where the wizard only chose a category (see the "plan" questions).
`;
}
