import type { DecisionRecord } from "@prisma/client";
import type { ProjectKnowledge } from "@/lib/knowledge/types";

// Project types the dev kit's checklist content has actually been tailored for. Others
// don't get a download link rather than shipping generic, unverified content as if real.
export const DEVKIT_SUPPORTED_TYPES = new Set(["Static website"]);

const NOT_DECIDED = "Not yet decided — revisit after finishing the ArchitectCoach interview.";

function orNotDecided(value: string): string {
  return value.trim() ? value : NOT_DECIDED;
}

function slugify(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

/**
 * Generates a tailored "AI Dev Kit" — docs filled in with this project's actual
 * ArchitectCoach answers, adapted from the ai-dev-kit/practices templates — as a
 * {filePath: content} map ready to zip. Currently tailored for the "Static website"
 * project type only; other types would need their own conditionals added below.
 */
export function generateDevKitFiles(
  projectName: string,
  knowledge: ProjectKnowledge,
  decisions: DecisionRecord[]
): Record<string, string> {
  const files: Record<string, string> = {};

  files["README.md"] = buildReadme(projectName, knowledge, decisions);
  files["docs/coding-standards.md"] = buildCodingStandards(knowledge);
  files["docs/testing-standards.md"] = buildTestingStandards(knowledge);
  files["docs/security-checklist.md"] = buildSecurityChecklist(knowledge);
  files["docs/performance-checklist.md"] = buildPerformanceChecklist(knowledge);
  files["docs/cost-checklist.md"] = buildCostChecklist(knowledge);
  files["docs/accessibility-checklist.md"] = buildAccessibilityChecklist();
  files["docs/definition-of-done.md"] = buildDefinitionOfDone();
  files["docs/review-checklist.md"] = buildReviewChecklist();
  files["docs/ai-collaboration.md"] = buildAiCollaboration(projectName);
  files["docs/local-setup-checklist.md"] = buildLocalSetupChecklist(knowledge);
  files[".github/PULL_REQUEST_TEMPLATE.md"] = buildPrTemplate();
  files["docs/decisions/README.md"] = buildDecisionsIndex(decisions);
  for (const d of decisions) {
    files[`docs/decisions/${String(d.number).padStart(4, "0")}-${slugify(d.title)}.md`] = buildAdr(d);
  }

  return files;
}

function buildReadme(projectName: string, k: ProjectKnowledge, decisions: DecisionRecord[]): string {
  const decisionLines = decisions.length
    ? decisions.map((d) => `- ${d.title}: ${d.decision}`).join("\n")
    : "None recorded yet — finish the ArchitectCoach interview first.";

  return `# ${projectName} — AI Dev Kit

Generated by ArchitectCoach from the decisions made in its interview wizard. Copy \`docs/\`
and \`.github/\` from this kit into your project (merge if they already exist), then read
\`docs/definition-of-done.md\` and \`docs/review-checklist.md\` first — everything else fills
in as you build.

## What's in this kit

- \`docs/coding-standards.md\` — conventions for the build approach you picked
- \`docs/testing-standards.md\` — what "tested" means for a project like this
- \`docs/security-checklist.md\`, \`docs/performance-checklist.md\`, \`docs/cost-checklist.md\`,
  \`docs/accessibility-checklist.md\` — four focused review checklists, each scoped to what
  actually applies to this project rather than a generic list
- \`docs/definition-of-done.md\`, \`docs/review-checklist.md\` — what "done" means and what a
  reviewer (human or AI) should check before approving a change
- \`docs/ai-collaboration.md\` — how to work with an AI coding assistant on this project
- \`docs/local-setup-checklist.md\` — how to get this running on a second machine
- \`.github/PULL_REQUEST_TEMPLATE.md\` — PR description template
- \`docs/decisions/\` — every decision recorded during the interview, as ADRs (Architecture
  Decision Records) — read these before changing something a past decision was based on

## This project, in one line

${orNotDecided(k.requirements.purpose)}

## Decisions captured so far

${decisionLines}
`;
}

function buildCodingStandards(k: ProjectKnowledge): string {
  const style = k.architecture.style;
  let toolingSection: string;

  if (style.includes("Static site generator")) {
    toolingSection = `This project uses a static site generator. Conventions:
- Content and templates live wherever the generator expects them (e.g. \`_layouts\`, \`content/\`) — never hand-edit the generated build output directory.
- Run the generator's build command before committing any change to content or templates, to catch build errors early rather than at deploy time.
- Keep the generator's config file the single source of truth for site-wide settings (title, base URL, navigation) — don't hardcode them per page.`;
  } else if (style.includes("Component framework")) {
    toolingSection = `This project uses a component framework exported as static files. Conventions:
- Components are the unit of reuse — don't duplicate markup across pages that could be one shared component.
- Before adding a feature, confirm it stays compatible with static export mode — some framework features require a live server and silently break static export.
- Run the actual static export build locally before pushing; export-time errors don't always show up in the dev server.`;
  } else {
    toolingSection = `This project is plain HTML, CSS, and JavaScript with no build step. Conventions:
- There's no templating, so shared markup (nav, footer) has to be kept in sync by hand across pages — a review question is "did this change need to happen on every page, and did it?"
- Prefer one shared stylesheet over inline styles or per-page \`<style>\` blocks, so visual conventions stay in one place.
- Keep JavaScript minimal. The architecture decision here was deliberately to avoid a framework/build step — don't let one back in through a JS library.`;
  }

  return `# Coding standards

## Build approach

${orNotDecided(style)}

${toolingSection}

## Naming and structure

- File and folder names: lowercase, hyphen-separated (e.g. \`about-us.html\`, \`blog-post-name.md\`).
- Keep a page's own assets near that page rather than in one giant shared folder, unless the asset is genuinely reused elsewhere.

## Formatting

- Use a formatter (Prettier, or the generator's built-in formatting) and run it before committing — don't review whitespace by eye.

## Accessibility baseline

Treated as a coding standard, not an afterthought — see \`accessibility-checklist.md\` for what to check on every page added.
`;
}

function buildTestingStandards(k: ProjectKnowledge): string {
  const goal = k.requirements.goals[0] ?? "";
  return `# Testing standards

## What "tested" means for this project

This is a static site — there's no application logic to unit test the way a backend project
would. What actually catches regressions here:

1. **Links stay valid.** Add a link checker (e.g. \`linkinator\`, or the site generator's own
   equivalent) to CI, run on every push.
2. **HTML is valid.** Run an HTML validator (e.g. \`html-validate\`) against the built output.
3. **Pages don't regress in performance or accessibility.** Run Lighthouse CI against the
   pages that matter most${goal ? ` — for this project, that's whichever page(s) support "${goal}"` : ""}, and fail the build if scores drop below an agreed threshold.

## Before merging

- [ ] Build succeeds locally (or via the host's deploy preview, if it provides one).
- [ ] Every new or changed page loads with no console errors and no broken links.
- [ ] Lighthouse accessibility score checked for any new or changed page.

## Opting out

If this project is small enough that CI-enforced checks aren't worth the setup yet (e.g. a
single-page personal site), say so explicitly here rather than silently having none — an
honest "not doing this yet" is more useful than a stale checklist nobody follows.
`;
}

function buildSecurityChecklist(k: ProjectKnowledge): string {
  const services = k.technology.thirdPartyServices;
  const hosting = orNotDecided(k.technology.hosting);
  const usesGoogleAnalytics = services.some((s) => s.includes("Google Analytics"));
  const usesPrivacyAnalytics = services.some((s) => s.includes("Privacy-friendly"));
  const usesNoAnalytics = services.some((s) => s.includes("No analytics")) || services.length === 0;

  let analyticsNote: string;
  if (usesGoogleAnalytics) {
    analyticsNote =
      "Google Analytics is enabled. It collects visitor data (IP-derived location, device info, behavior) — check whether your audience's jurisdiction (e.g. EU/UK) requires a cookie-consent banner or a published privacy policy before it goes live.";
  } else if (usesPrivacyAnalytics) {
    analyticsNote =
      "A privacy-friendly, cookie-free analytics tool is enabled — this avoids most consent-banner requirements, but verify against your specific audience's jurisdiction if that matters here.";
  } else if (usesNoAnalytics) {
    analyticsNote = "No analytics is enabled — no visitor data is collected by this site.";
  } else {
    analyticsNote = NOT_DECIDED;
  }

  return `# Security checklist

## 1. Data sensitivity posture

This is a static site with no login, no user accounts, and no database — the threat model
here is much smaller than a typical web app. ${analyticsNote}

## Secrets

- Deploy credentials for ${hosting} (an API token or deploy key) live in your CI provider's
  encrypted secrets (e.g. GitHub Actions secrets), never committed to the repo.
- If a third-party form service is ever added, its API key is a secret too — same rule.

## Third-party data exposure

${services.length ? services.map((s) => `- ${s}`).join("\n") : "None — no third-party scripts are loaded."}

## Injection / untrusted input

Not applicable — this project has no backend or database to inject into. If a contact form is
added that posts anywhere other than a trusted third-party form service, revisit this section.

## Network exposure

- Auth: none — the site is intentionally fully public.
- HTTPS: ${hosting} provides this automatically for a custom domain; don't disable it.
- CORS: not applicable — this project has no API of its own.

## Dependencies

${
  k.architecture.style.includes("Plain HTML")
    ? "No build-tool dependencies — nothing to audit."
    : "Run `npm audit` (or the build tool's equivalent) periodically. A compromised build-time dependency can't reach visitors directly, but it could inject something into the site output during a build."
}

## Reporting a concern

No formal process yet — small project, no external users. Add contact info here once that's
no longer true.
`;
}

function buildPerformanceChecklist(k: ProjectKnowledge): string {
  const hosting = orNotDecided(k.technology.hosting);
  return `# Performance checklist

Scoped to what matters for a static site — not a generic web-performance checklist.

## Page weight

- [ ] Images are compressed and sized for their actual display size, not the camera's original resolution.
- [ ] No unused CSS/JS is shipped to every page (especially relevant if using a component framework export, where bundling can pull in more than one page needs).

## Loading strategy

- [ ] Images below the fold use \`loading="lazy"\`.
- [ ] Fonts are loaded with \`font-display: swap\` (or self-hosted) so text isn't invisible while a web font loads.

## Hosting/CDN

- ${hosting} serves static assets from a CDN by default — don't add unnecessary caching logic on top of what it already provides.
- Set long cache lifetimes for versioned/hashed assets (images, compiled CSS/JS); shorter ones for HTML pages that change.

## Measuring it

- [ ] Run Lighthouse (or PageSpeed Insights) against the homepage and the page that matters most for the project's main goal, before considering a launch done.
- [ ] Track Core Web Vitals (LCP, CLS, INP) — a passing Lighthouse score today can regress silently as content grows; re-check periodically, not just once.
`;
}

function buildCostChecklist(k: ProjectKnowledge): string {
  const hosting = k.technology.hosting;
  const services = k.technology.thirdPartyServices;

  let hostingNote: string;
  if (hosting.includes("GitHub Pages")) {
    hostingNote = "GitHub Pages is free with no bandwidth billing surprises for a normal static site — the main cost risk is none, short of GitHub changing its terms.";
  } else if (hosting.includes("Netlify")) {
    hostingNote = "Netlify's free tier covers a generous amount of bandwidth and build minutes for a small site — the cost risk is exceeding the free tier's bandwidth or build-minute allowance if traffic or deploy frequency grows a lot.";
  } else if (hosting.includes("Vercel")) {
    hostingNote = "Vercel's free (Hobby) tier is for personal/non-commercial use — if this site starts generating revenue, check whether it needs to move to a paid plan.";
  } else if (hosting.includes("Traditional")) {
    hostingNote = "Traditional hosting is usually a fixed monthly fee regardless of traffic — predictable cost, but you're paying even during low-traffic periods, unlike the usage-based free tiers above.";
  } else {
    hostingNote = NOT_DECIDED;
  }

  const analyticsNote = services.some((s) => s.includes("Google Analytics"))
    ? "Google Analytics is free."
    : services.some((s) => s.includes("Privacy-friendly"))
      ? "Privacy-friendly analytics tools are typically a small paid monthly subscription (e.g. Plausible, Fathom) — factor that recurring cost in, however small."
      : "No analytics cost, since none is enabled.";

  return `# Cost checklist

## Hosting

${hostingNote}

## Analytics

${analyticsNote}

## Domain

- Domain registration (~$10-20/year typically) is a separate cost from hosting — don't forget to budget for renewal, and set the registrar to auto-renew so the domain doesn't lapse unexpectedly.

## Growth triggers to watch

- [ ] Bandwidth/build-minute usage approaching the hosting free tier's limit.
- [ ] Any new third-party service added later (forms, search, comments) — check its pricing tier before adopting it, not after it's already load-bearing.
`;
}

function buildAccessibilityChecklist(): string {
  return `# Accessibility checklist

## Structure

- [ ] Headings are used in order (one \`<h1>\` per page, no skipped levels) — not just styled to look like headings.
- [ ] Semantic HTML elements (\`<nav>\`, \`<main>\`, \`<button>\`, \`<a>\`) are used instead of generic \`<div>\`/\`<span>\` with click handlers.

## Images and media

- [ ] Every meaningful image has descriptive \`alt\` text; purely decorative images use \`alt=""\`.
- [ ] Any video has captions if it conveys information through audio.

## Color and contrast

- [ ] Text meets WCAG AA contrast ratio against its background (4.5:1 for normal text, 3:1 for large text).
- [ ] Color isn't the only way information is conveyed (e.g. a link isn't distinguished from body text by color alone).

## Keyboard and forms

- [ ] Every interactive element (links, buttons, form fields) is reachable and usable via keyboard alone, in a sensible tab order.
- [ ] Any form field has a real \`<label>\`, not just placeholder text.

## Verifying it

- [ ] Run an automated checker (axe, or Lighthouse's accessibility audit) against every new page — it won't catch everything, but it catches the common mistakes cheaply.
`;
}

function buildDefinitionOfDone(): string {
  return `# Definition of Done

A change is done when:

- [ ] It does what it was meant to do, verified by actually loading the page(s) affected — not just "the build succeeded."
- [ ] It passes the checks in \`testing-standards.md\` (link check, HTML validity, Lighthouse thresholds).
- [ ] Anything in \`security-checklist.md\`, \`performance-checklist.md\`, or \`accessibility-checklist.md\` that this change touches has been checked, not assumed fine.
- [ ] Any doc this change makes stale (this kit's docs, or the project's own README) is updated in the same change, not left for later.
- [ ] If this change involved a genuinely new decision (not just an implementation detail), it's recorded as an ADR in \`decisions/\`.
`;
}

function buildReviewChecklist(): string {
  return `# Review checklist

What a reviewer (human or AI) should actually check before approving a change.

## Correctness

- [ ] Does the change do what its description says? Re-derive this from the diff — don't just trust the description.
- [ ] Was it actually loaded in a browser, not just built successfully?

## Security / performance / accessibility

- [ ] Anything relevant in \`security-checklist.md\`, \`performance-checklist.md\`, or \`accessibility-checklist.md\` — checked, or does one of those docs need updating?

## Scope

- [ ] Does the change do one coherent thing? A content update bundled with an unrelated redesign makes both harder to review and harder to revert independently.
- [ ] Is there speculative/unused markup, config, or a feature flag added for a need that doesn't exist yet? Flag it.

## Docs

- [ ] Is a genuinely new decision (not just an implementation detail) recorded as an ADR in \`decisions/\`?
`;
}

function buildAiCollaboration(projectName: string): string {
  return `# Working with an AI coding assistant on ${projectName}

- Point your assistant at this \`docs/\` folder at the start of a session — it has the actual
  decisions and standards for this project, not generic defaults.
- Before asking it to implement something that touches a documented decision (build approach,
  hosting, analytics), have it read the relevant ADR in \`decisions/\` first.
- Ask it to update the relevant doc in the same change when it makes a new non-trivial
  decision, rather than leaving that decision undocumented.
- Treat its output the way you'd treat a junior contributor's PR: read the diff, don't just
  trust the summary of what it says it did.
`;
}

function buildLocalSetupChecklist(k: ProjectKnowledge): string {
  const style = k.architecture.style;
  let buildStep: string;
  if (style.includes("Static site generator")) {
    buildStep = "- [ ] Install Node.js and run `npm install`, then the generator's dev-server command (e.g. `npm run dev` / `npm start`, check its docs) to preview locally.";
  } else if (style.includes("Component framework")) {
    buildStep = "- [ ] Install Node.js and run `npm install`, then the framework's dev command to preview locally, and its static-export build command to confirm the export still works.";
  } else {
    buildStep = "- [ ] No build step — open the HTML files directly in a browser, or run any static file server (e.g. `npx serve`) to preview with correct relative paths.";
  }

  return `# Local setup checklist

- [ ] Clone the repo.
${buildStep}
- [ ] Confirm the site matches what's currently deployed before making changes.
- [ ] Read \`docs/coding-standards.md\` for this project's specific conventions before your first commit.
`;
}

function buildPrTemplate(): string {
  return `## What changed and why

## How to verify

- [ ] Loaded the affected page(s) in a browser
- [ ] Checked against \`testing-standards.md\`

## Checklist

- [ ] Relevant checklist(s) in \`docs/\` reviewed (security / performance / accessibility)
- [ ] New non-trivial decisions recorded as an ADR in \`docs/decisions/\`
`;
}

function buildDecisionsIndex(decisions: DecisionRecord[]): string {
  if (!decisions.length) {
    return `# Decisions

None recorded yet — finish the ArchitectCoach interview first, then re-download this kit.
`;
  }
  const rows = decisions
    .map((d) => `| ${d.number} | [${d.title}](./${String(d.number).padStart(4, "0")}-${slugify(d.title)}.md) | ${d.section} |`)
    .join("\n");
  return `# Decisions

| # | Title | Section |
|---|---|---|
${rows}
`;
}

function buildAdr(d: DecisionRecord): string {
  const learnMore = d.learnMore.length
    ? `\n\n## Learn more\n\n${d.learnMore.map((t) => `- ${t}`).join("\n")}\n`
    : "";
  return `# ADR-${String(d.number).padStart(4, "0")}: ${d.title}

**Status:** ${d.status}
**Date:** ${d.createdAt.toISOString().slice(0, 10)}

## Context

${d.rationale}

## Decision

${d.decision}

## Alternatives considered

${d.alternatives || "None recorded."}

## Consequences

${d.tradeoffs}${d.consequences ? `\n\n${d.consequences}` : ""}${learnMore}`;
}
